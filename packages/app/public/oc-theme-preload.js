;(function () {
  var key = "opencode-theme-id"
  // Panacode defaults to its own theme; oc-2 remains available once chosen.
  var themeId = localStorage.getItem(key) || "panacode"

  var scheme = localStorage.getItem("opencode-color-scheme") || document.documentElement.dataset.defaultColorScheme || "dark"
  var nativeMode = window.electron && window.electron.bootstrap && window.electron.bootstrap.systemMode
  var systemDark = nativeMode ? nativeMode === "dark" : matchMedia("(prefers-color-scheme: dark)").matches
  var isDark = scheme === "dark" || (scheme === "system" && systemDark)
  var mode = isDark ? "dark" : "light"
  // panacode-brand:begin (generated by script/panacode-brand-apply.ts)
  var brandSeed = {"darkPaper":"#0B0E17","lightPaper":"#F5F3EE","dark":":root[data-theme=\"panacode\"]{color-scheme:dark;--background-base:#0B0E17;--text-strong:#F3F2F5;--text-weak:#A7A7B1;--input-base:#14161D;--icon-base:#D1CFD7;--icon-weak-base:#A7A7B1;--icon-strong-base:#F3F2F5;--v2-background-bg-base:#17191F;--v2-background-bg-deep:#0B0E17;--v2-text-text-base:#F3F2F5;}","light":":root[data-theme=\"panacode\"]{color-scheme:light;--background-base:#F5F3EE;--text-strong:#29271F;--text-weak:#6D665A;--input-base:#FFFDF9;--icon-base:#4C463C;--icon-weak-base:#6D665A;--icon-strong-base:#29271F;--v2-background-bg-base:#FFFDF8;--v2-background-bg-deep:#F5F3EE;--v2-text-text-base:#29271F;}"}
  // panacode-brand:end
  var paper = themeId === "panacode" ? (isDark ? brandSeed.darkPaper : brandSeed.lightPaper) : (isDark ? "#080808" : "#fafafa")

  document.documentElement.dataset.theme = themeId
  document.documentElement.dataset.colorScheme = mode
  document.documentElement.dataset.brand = "panacode"
  document.documentElement.style.backgroundColor = paper
  document.documentElement.style.colorScheme = mode

  // Seed high-contrast ink/surface before theme CSS arrives so splash + error
  // logs never render black-on-black or white-on-white on first paint.
  var seed = document.createElement("style")
  seed.id = "oc-theme-preload-seed"
  seed.textContent = themeId === "panacode" ? (isDark ? brandSeed.dark : brandSeed.light) : isDark
    ? ":root{color-scheme:dark;--text-strong:#ededed;--text-weak:#707070;--input-base:#1c1c1c;--icon-base:#7e7e7e;--icon-weak-base:#a0a0a0;--icon-strong-base:#ededed;--v2-background-bg-base:#161616;--v2-background-bg-deep:#080808;--v2-text-text-base:#ededed;}"
    : ":root{color-scheme:light;--text-strong:#171717;--text-weak:#8f8f8f;--input-base:#fcfcfc;--icon-base:#8f8f8f;--icon-weak-base:#c7c7c7;--icon-strong-base:#171717;--v2-background-bg-base:#fafafa;--v2-background-bg-deep:#f2f2f2;--v2-text-text-base:#171717;}"
  document.head.appendChild(seed)

  // Update theme-color meta tag to match app color scheme
  var metas = document.querySelectorAll("meta[name='theme-color']")
  if (metas.length > 0) metas[0].setAttribute("content", paper)

  // Built-in themes ship CSS with the app bundle; only custom themes need cached CSS before paint.
  if (themeId === "oc-2" || themeId === "panacode") return

  var css = localStorage.getItem("opencode-theme-css-" + mode)
  if (css) {
    var style = document.createElement("style")
    style.id = "oc-theme-preload"
    style.textContent =
      ":root{color-scheme:" +
      mode +
      ";--text-mix-blend-mode:" +
      (isDark ? "plus-lighter" : "multiply") +
      ";" +
      css +
      "}"
    document.head.appendChild(style)
  }
})()
