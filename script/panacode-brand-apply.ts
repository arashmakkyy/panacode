#!/usr/bin/env bun
/**
 * Switch the active Panacode brand pack and regenerate everything derived from it.
 *
 *   bun script/panacode-brand-apply.ts <pack>        e.g. firouzeh
 *
 * 1. Points packages/panacode-ui/src/brand/active.ts and active.css at packs/<pack>.
 * 2. Writes the pack's palette into the OpenCode-side theme packages/ui/src/theme/themes/panacode.json
 *    (grey ramp, accent tokens, legacy overrides), so every upstream surface follows the brand.
 * 3. Rasterises packs/<pack>/assets/icon-1024.png into the desktop icons and web favicons (python3 + Pillow).
 */
import path from "node:path"
import { $ } from "bun"

const name = process.argv[2]
if (!name) throw new Error("usage: bun script/panacode-brand-apply.ts <pack>")
const root = path.resolve(import.meta.dir, "..")
const brandDir = path.join(root, "packages/panacode-ui/src/brand")
const packDir = path.join(brandDir, "packs", name)
if (!(await Bun.file(path.join(packDir, "brand.ts")).exists())) throw new Error(`no brand pack at ${packDir}`)

await Bun.write(
  path.join(brandDir, "active.ts"),
  `/*
 * The active Panacode brand pack. This file and active.css are the only places that name a pack.
 * Swap with \`bun script/panacode-brand-apply.ts <pack>\` (see packages/panacode-ui/src/brand/README.md).
 */
export { brand, brandIcon, BrandMark, BrandWordmark, BrandLockup } from "./packs/${name}"
export { pack } from "./packs/${name}/brand"
`,
)
await Bun.write(
  path.join(brandDir, "active.css"),
  `/* Active brand pack styles. Kept in step with active.ts by script/panacode-brand-apply.ts. */
@import "./packs/${name}/fonts.css";
@import "./packs/${name}/tokens.css";
`,
)

const { pack } = await import(path.join(packDir, "brand.ts"))
const themePath = path.join(root, "packages/ui/src/theme/themes/panacode.json")
// Start from Classic so swapping packs cannot carry over the previous pack's overrides.
const theme = await Bun.file(path.join(path.dirname(themePath), "oc-2.json")).json()
theme.name = pack.name
theme.id = "panacode"
for (const scheme of ["light", "dark"] as const) {
  const src = pack.theme[scheme]
  const target = theme[scheme]
  Object.assign(target.palette, src.palette)
  Object.assign(target.overrides, src.overrides)
  for (const [step, hex] of Object.entries(src.grey)) target.v2Overrides[`v2-grey-${step}`] = `${hex}ff`.toLowerCase()
  // Older packs specify only an accent. New packs can map every workbench role.
  if (src.accent) Object.assign(target.v2Overrides, {
    "v2-background-bg-accent": src.accent.bg,
    "v2-text-text-accent": src.accent.text,
    "v2-text-text-accent-hover": src.accent.hover,
    "v2-text-text-code-accent": src.accent.text,
    "v2-text-text-code-path": src.accent.codePath,
    "v2-icon-icon-accent": src.accent.text,
    "v2-icon-icon-accent-hover": src.accent.hover,
    "v2-border-border-focus": src.accent.focus,
  })
  Object.assign(target.v2Overrides, src.v2Overrides)
}
await Bun.write(themePath, JSON.stringify(theme, null, 2) + "\n")
console.log(`theme: ${path.relative(root, themePath)}`)

if (!process.argv.includes("--colors-only")) {
  await $`python3 ${path.join(root, "script/panacode-brand-icons.py")} ${packDir}`
}
console.log(`active brand: ${name}`)

// First-paint seed: the preload script paints the window before theme CSS loads.
const preloadPath = path.join(root, "packages/app/public/oc-theme-preload.js")
const paper = (scheme: "light" | "dark") => {
  const t = pack.theme[scheme]
  return t.v2Overrides?.["v2-background-bg-deep"] ?? t.grey[scheme === "dark" ? "1200" : "200"]
}
const seed = (scheme: "light" | "dark") => {
  const t = pack.theme[scheme]
  const panel = t.v2Overrides?.["v2-background-bg-base"] ?? t.grey[scheme === "dark" ? "1100" : "100"]
  const o = t.overrides as Record<string, string>
  return (
    `:root[data-theme="panacode"]{color-scheme:${scheme};--background-base:${o["background-base"] ?? paper(scheme)};--text-strong:${o["text-strong"]};--text-weak:${o["text-weak"]};` +
    `--input-base:${o["input-base"] ?? t.grey[scheme === "dark" ? "1000" : "50"]};--icon-base:${o["icon-base"]};--icon-weak-base:${o["icon-weak-base"]};` +
    `--icon-strong-base:${o["text-strong"]};--v2-background-bg-base:${panel};` +
    `--v2-background-bg-deep:${paper(scheme)};--v2-text-text-base:${o["text-strong"]};}`
  )
}
const block = `  // panacode-brand:begin (generated by script/panacode-brand-apply.ts)\n  var brandSeed = ${JSON.stringify({
  darkPaper: paper("dark"),
  lightPaper: paper("light"),
  dark: seed("dark"),
  light: seed("light"),
})}\n  // panacode-brand:end\n`
const preload = await Bun.file(preloadPath).text()
await Bun.write(preloadPath, preload.replace(/  \/\/ panacode-brand:begin[\s\S]*?\/\/ panacode-brand:end\n/, block))
console.log(`preload seed: ${path.relative(root, preloadPath)}`)
